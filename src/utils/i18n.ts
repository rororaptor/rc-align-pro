// i18n Internationalization Engine for RC Alignment Pro
import { AppLanguage, ValueDisplayFormat } from '../types';

export type SupportedLocale = 'fr' | 'en' | 'de';

export function resolveEffectiveLocale(lang: AppLanguage): SupportedLocale {
  if (lang === 'fr' || lang === 'en' || lang === 'de') {
    return lang;
  }
  return 'fr';
}

export function formatAngleValue(
  value: number | null,
  format: ValueDisplayFormat = 'integer',
  includePlus = false
): string {
  if (value === null || isNaN(value)) return '--';
  if (format === 'step05') {
    const rounded = Math.round(value * 2) / 2;
    const fixed = (Object.is(rounded, -0) ? 0 : rounded).toFixed(1);
    const prefix = includePlus && Number(fixed) > 0 ? '+' : '';
    return `${prefix}${fixed}°`;
  }
  const rounded = Math.round(value);
  const formatted = (Object.is(rounded, -0) ? 0 : rounded).toString();
  const prefix = includePlus && Number(formatted) > 0 ? '+' : '';
  return `${prefix}${formatted}°`;
}

